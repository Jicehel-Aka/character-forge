/**
 * RGB565 and RGB565_LE conversion utilities for ESPBoy, AKA, Arduboy, and retro microcontrollers.
 */

export interface RGB565ConversionResult {
  width: number;
  height: number;
  totalPixels: number;
  byteLength: number;
  words: Uint16Array;
  bytesLE: Uint8Array;
  bytesBE: Uint8Array;
  cHeader: string;
  palette: string[];
}

/**
 * Converts a 24/32-bit RGB(A) color to 16-bit 5-6-5 format.
 */
export function colorToRGB565(r: number, g: number, b: number): number {
  const r5 = (r >> 3) & 0x1f;
  const g6 = (g >> 2) & 0x3f;
  const b5 = (b >> 3) & 0x1f;
  return (r5 << 11) | (g6 << 5) | b5;
}

/**
 * Converts a 16-bit RGB565 word back to RGBA [r, g, b, 255] for preview.
 */
export function rgb565ToRgba(word: number): [number, number, number, number] {
  const r5 = (word >> 11) & 0x1f;
  const g6 = (word >> 5) & 0x3f;
  const b5 = word & 0x1f;

  const r = Math.round((r5 * 255) / 31);
  const g = Math.round((g6 * 255) / 63);
  const b = Math.round((b5 * 255) / 31);
  return [r, g, b, 255];
}

/**
 * Converts ImageData to RGB565 buffers and C PROGMEM headers.
 */
export function imageToRGB565(
  imageData: ImageData,
  assetName: string = 'sprite',
  transparentColorKey?: { r: number; g: number; b: number }
): RGB565ConversionResult {
  const width = imageData.width;
  const height = imageData.height;
  const totalPixels = width * height;
  const data = imageData.data;

  const words = new Uint16Array(totalPixels);
  const bytesLE = new Uint8Array(totalPixels * 2);
  const bytesBE = new Uint8Array(totalPixels * 2);

  const colorCounts = new Map<number, number>();

  for (let i = 0; i < totalPixels; i++) {
    const idx = i * 4;
    let r = data[idx];
    let g = data[idx + 1];
    let b = data[idx + 2];
    const a = data[idx + 3];

    // If fully transparent, substitute with chroma key or black
    if (a < 128) {
      if (transparentColorKey) {
        r = transparentColorKey.r;
        g = transparentColorKey.g;
        b = transparentColorKey.b;
      } else {
        r = 0;
        g = 0;
        b = 0;
      }
    }

    const rgb565 = colorToRGB565(r, g, b);
    words[i] = rgb565;

    // Track color counts for palette
    colorCounts.set(rgb565, (colorCounts.get(rgb565) || 0) + 1);

    // Little-Endian (ESPBoy / AKA TFT standard: low byte first)
    bytesLE[i * 2] = rgb565 & 0xff;
    bytesLE[i * 2 + 1] = (rgb565 >> 8) & 0xff;

    // Big-Endian (high byte first)
    bytesBE[i * 2] = (rgb565 >> 8) & 0xff;
    bytesBE[i * 2 + 1] = rgb565 & 0xff;
  }

  // Extract top palette colors in hex
  const sortedColors = Array.from(colorCounts.entries())
    .sort((a, b) => b[1] - a[1])
    .slice(0, 16)
    .map(([val]) => {
      const [r, g, b] = rgb565ToRgba(val);
      return `#${((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1).toUpperCase()}`;
    });

  // Generate C/C++ header code
  const sanitizedName = assetName.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const cHeader = generateCHeader(sanitizedName, width, height, words);

  return {
    width,
    height,
    totalPixels,
    byteLength: totalPixels * 2,
    words,
    bytesLE,
    bytesBE,
    cHeader,
    palette: sortedColors,
  };
}

function generateCHeader(name: string, width: number, height: number, words: Uint16Array): string {
  const upper = name.toUpperCase();
  const hexLines: string[] = [];
  const itemsPerLine = 12;

  for (let i = 0; i < words.length; i += itemsPerLine) {
    const chunk = Array.from(words.subarray(i, i + itemsPerLine)).map(
      (w) => `0x${w.toString(16).padStart(4, '0').toUpperCase()}`
    );
    hexLines.push('    ' + chunk.join(', '));
  }

  return `// Generated by Asset Recovery Agent for ESPBoy / AKA
// Target: ESP8266 / ESP32 TFT (RGB565 Little-Endian compatible)
#ifndef _${upper}_H_
#define _${upper}_H_

#include <stdint.h>
#if defined(ESP8266) || defined(ESP32) || defined(ARDUINO_ARCH_AVR)
  #include <avr/pgmspace.h>
#else
  #define PROGMEM
#endif

#define ${upper}_WIDTH   ${width}
#define ${upper}_HEIGHT  ${height}
#define ${upper}_BYTES   ${words.length * 2}

// 16-bit RGB565 Pixel Data (${width}x${height}, ${words.length} pixels)
const uint16_t ${name}_bitmap[${words.length}] PROGMEM = {
${hexLines.join(',\n')}
};

#endif // _${upper}_H_
`;
}
